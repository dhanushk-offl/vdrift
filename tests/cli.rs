//! End-to-end CLI tests: fixture creation, git repos, adapter matrices,
//! exit codes, and the pre-push hook guards.

use std::fs;
use std::path::Path;
use std::process::{Command, Output};

const BIN: &str = env!("CARGO_BIN_EXE_vdrift");

fn vdrift() -> Command {
    let mut c = Command::new(BIN);
    c.env_remove("CI")
        .env_remove("VDRIFT_SKIP")
        .env_remove("VDRIFT_RUNNING");
    c
}

fn run(c: &mut Command) -> Output {
    c.output().expect("failed to run vdrift")
}

fn stdout(o: &Output) -> String {
    String::from_utf8_lossy(&o.stdout).into_owned()
}

fn stderr(o: &Output) -> String {
    String::from_utf8_lossy(&o.stderr).into_owned()
}

fn git(dir: &Path, args: &[&str]) {
    let out = Command::new("git")
        .arg("-C")
        .arg(dir)
        .args(args)
        .output()
        .expect("failed to run git");
    assert!(
        out.status.success(),
        "git {args:?}: {}",
        String::from_utf8_lossy(&out.stderr)
    );
}

fn write(path: &Path, contents: &str) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, contents).unwrap();
}

/// Creates a temp dir initialized as a git repo with a test identity.
fn fixture(name: &str) -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path();
    git(root, &["init", "-q", "-b", "main"]);
    git(root, &["config", "user.email", "test@example.com"]);
    git(root, &["config", "user.name", "Test User"]);
    let _ = name;
    dir
}

fn commit_all(dir: &Path, message: &str) {
    git(dir, &["add", "-A"]);
    git(dir, &["commit", "-q", "-m", message]);
}

fn init_npm_fixture(dir: &Path) {
    write(
        &dir.join("package.json"),
        r#"{
  "name": "app",
  "version": "2.0.0"
}
"#,
    );
    write(
        &dir.join("README.md"),
        "# app v2.0.0\n\nUse version 1.9.0 with npm:\n\n    npm install app@1.9.0\n",
    );
    commit_all(dir, "chore: initial");
}

// ---------------------------------------------------------------- detection

#[test]
fn npm_scan_detects_canonical_and_candidate() {
    let d = fixture("scan");
    init_npm_fixture(d.path());

    let out = run(vdrift().args(["scan", "--json"]).current_dir(d.path()));
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    let v: serde_json::Value = serde_json::from_str(&stdout(&out)).unwrap();
    assert_eq!(v["project"]["type"], "node");
    assert_eq!(v["sources"][0]["file"], "package.json");
    assert_eq!(v["sources"][0]["version"], "2.0.0");
    assert_eq!(v["sources"][0]["kind"], "canonical");
    let readmes: Vec<_> = v["candidates"]
        .as_array()
        .unwrap()
        .iter()
        .filter(|c| c["file"].as_str().unwrap().ends_with("README.md"))
        .collect();
    assert_eq!(readmes.len(), 1);
}

