// --------------------------------------------------------- global integration

#[test]
fn init_status_uninstall_roundtrip() {
    let base = tempfile::tempdir().unwrap();
    let config_home = base.path().join("xdg");
    fs::create_dir_all(&config_home).unwrap();

    let mut c = vdrift();
    c.args(["init"]).env("XDG_CONFIG_HOME", &config_home);
    let out = run(&mut c);
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));

    let hooks_path = Command::new("git")
        .args(["config", "--global", "core.hooksPath"])
        .env("XDG_CONFIG_HOME", &config_home)
        .output()
        .unwrap();
    let hp = String::from_utf8_lossy(&hooks_path.stdout)
        .trim()
        .to_string();
    assert!(hp.contains("vdrift/hooks"), "unexpected hooksPath: {hp}");

    let dispatcher = config_home.join("vdrift/hooks/pre-push");
    assert!(dispatcher.is_file(), "dispatcher hook not written");

    let out = run(vdrift()
        .args(["status"])
        .env("XDG_CONFIG_HOME", &config_home));
    assert_eq!(out.status.code(), Some(0));

    // Uninstall is deterministic with --yes.
    let out = run(vdrift()
        .args(["uninstall", "--yes"])
        .env("XDG_CONFIG_HOME", &config_home));
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    assert!(!dispatcher.exists(), "dispatcher hook should be removed");
}

// ------------------------------------------------------------- agents (JSON)

#[test]
fn agent_workflow_is_deterministic() {
    let d = fixture("agent");
    init_npm_fixture(d.path());
    write(
        &d.path().join(".vdrift.toml"),
        "[references]\nfiles = [\"README.md\"]\n",
    );

    // 1. check --json
    let out = run(vdrift().args(["check", "--json"]).current_dir(d.path()));
    assert_eq!(out.status.code(), Some(1));
    let v: serde_json::Value = serde_json::from_str(&stdout(&out)).unwrap();
    assert_eq!(v["status"], "drift");
    let target = v["canonical"]["version"].as_str().unwrap().to_string();

    // 2. plan --json (read-only)
    let out = run(vdrift().args(["plan", "--json"]).current_dir(d.path()));
    assert_eq!(out.status.code(), Some(0));
    let _v: serde_json::Value = serde_json::from_str(&stdout(&out)).unwrap();

    // 3. apply --version --commit (deterministic, no prompts)
    let out = run(vdrift()
        .args(["apply", "--version", &target, "--commit", "--force"])
        .current_dir(d.path()));
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));

    // 4. verify --ci
    let out = run(vdrift().args(["verify", "--ci"]).current_dir(d.path()));
    assert_eq!(out.status.code(), Some(0), "{}", stdout(&out));
}
