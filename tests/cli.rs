// ------------------------------------------------------------------- hook

/// Writes the pre-push stdin line to the child. The hook may exit before
/// consuming stdin (early guards), so a broken pipe is acceptable.
fn feed_hook_stdin(child: &mut std::process::Child, line: &str) {
    use std::io::Write;
    if let Some(mut stdin) = child.stdin.take() {
        let _ = stdin.write_all(line.as_bytes());
    }
}

fn hook_stdin_line(dir: &Path, remote_oid: &str) -> String {
    let oid = Command::new("git")
        .arg("-C")
        .arg(dir)
        .args(["rev-parse", "HEAD"])
        .output()
        .unwrap();
    let oid = String::from_utf8_lossy(&oid.stdout).trim().to_string();
    format!("refs/heads/main {oid} refs/heads/main {remote_oid}")
}

#[test]
fn hook_skips_when_push_is_clean() {
    let d = fixture("hook_clean");
    init_npm_fixture(d.path());

    let mut c = vdrift();
    c.args(["hook", "pre-push"]).current_dir(d.path());
    c.stdin(std::process::Stdio::piped());
    let mut child = c.spawn().unwrap();
    feed_hook_stdin(
        &mut child,
        &hook_stdin_line(d.path(), "0000000000000000000000000000000000000000"),
    );
    let out = child.wait_with_output().unwrap();
    assert_eq!(out.status.code(), Some(0), "{}", stdout(&out));
}

