// -------------------------------------------------------------------- git

#[test]
fn apply_commit_creates_bump_commit() {
    let d = fixture("apply_commit");
    init_npm_fixture(d.path());

    let out = run(vdrift()
        .args(["apply", "--version", "2.1.0", "--commit"])
        .current_dir(d.path()));
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));

    let log = Command::new("git")
        .arg("-C")
        .arg(d.path())
        .args(["log", "-1", "--format=%s"])
        .output()
        .unwrap();
    assert_eq!(
        String::from_utf8_lossy(&log.stdout).trim(),
        "chore: bump version to 2.1.0"
    );
    let pkg: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(d.path().join("package.json")).unwrap()).unwrap();
    assert_eq!(pkg["version"], "2.1.0");
}

#[test]
fn apply_refuses_dirty_target_file() {
    let d = fixture("dirty");
    init_npm_fixture(d.path());
    write(
        &d.path().join(".vdrift.toml"),
        "[references]\nfiles = [\"README.md\"]\n",
    );
    // Uncommitted change to README that still carries a version.
    write(
        &d.path().join("README.md"),
        "# app\n\nUse 1.9.0 with npm.\n",
    );

    let out = run(vdrift().args(["sync"]).current_dir(d.path()));
    assert_eq!(out.status.code(), Some(6), "{}", stderr(&out));
    // Nothing was partially applied: package.json still has the old version.
    let pkg: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(d.path().join("package.json")).unwrap()).unwrap();
    assert_eq!(pkg["version"], "2.0.0");

    // --force overrides the guard.
    let out = run(vdrift().args(["sync", "--force"]).current_dir(d.path()));
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
}

