// ------------------------------------------------------------------ cargo

#[test]
fn cargo_lock_is_a_derived_reference() {
    let d = fixture("cargo");
    write(
        &d.path().join("Cargo.toml"),
        "[package]\nname = \"lib\"\nversion = \"0.3.1\"\n",
    );
    write(
        &d.path().join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = \"lib\"\nversion = \"0.3.1\"\n",
    );
    commit_all(d.path(), "chore: initial");

    let out = run(vdrift().args(["scan", "--json"]).current_dir(d.path()));
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    let v: serde_json::Value = serde_json::from_str(&stdout(&out)).unwrap();
    let kinds: Vec<&str> = v["sources"]
        .as_array()
        .unwrap()
        .iter()
        .map(|s| s["kind"].as_str().unwrap())
        .collect();
    assert!(kinds.contains(&"canonical"));
    assert!(kinds.contains(&"derived"));

    // Bump updates both manifest and lockfile.
    let out = run(vdrift()
        .args(["apply", "--version", "0.3.2", "--no-commit"])
        .current_dir(d.path()));
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    let lock = fs::read_to_string(d.path().join("Cargo.lock")).unwrap();
    assert!(lock.contains("version = \"0.3.2\""));
    let manifest = fs::read_to_string(d.path().join("Cargo.toml")).unwrap();
    assert!(manifest.contains("version = \"0.3.2\""));
}

// ------------------------------------------------------------- generic yaml

#[test]
fn generic_json_can_be_a_reference() {
    let d = fixture("jsonref");
    write(
        &d.path().join("helm/Chart.yaml"),
        "apiVersion: v2\nname: app\nversion: 3.1.0\n",
    );
    write(
        &d.path().join(".vdrift.toml"),
        "[version]\nsource = \"helm/Chart.yaml\"\n[references]\nfiles = [\"docs/version.json\"]\n",
    );
    write(
        &d.path().join("docs/version.json"),
        "{\n  \"version\": \"3.0.9\"\n}\n",
    );
    commit_all(d.path(), "chore: initial");

    let out = run(vdrift().args(["check", "--json"]).current_dir(d.path()));
    assert_eq!(out.status.code(), Some(1), "{}", stdout(&out));
    let v: serde_json::Value = serde_json::from_str(&stdout(&out)).unwrap();
    assert_eq!(v["canonical"]["file"], "helm/Chart.yaml");
    assert_eq!(v["canonical"]["version"], "3.1.0");

    let out = run(vdrift().args(["sync"]).current_dir(d.path()));
    assert_eq!(out.status.code(), Some(0), "{}", stderr(&out));
    let json = fs::read_to_string(d.path().join("docs/version.json")).unwrap();
    let v: serde_json::Value = serde_json::from_str(&json).unwrap();
    assert_eq!(v["version"], "3.1.0");
}

